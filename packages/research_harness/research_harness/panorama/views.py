"""L2 view layer: regenerable markdown vault projected from the panorama L1 store.

Views are caches:
they are never hand-edited, always safe to delete, and every synthesized
statement carries a back-link to its evidence anchor (`source_ref`).

Generation is deterministic: successive runs on unchanged data produce
byte-identical files except for the `generated_at` timestamp line, which sits
on its own line so diffs stay readable.
"""

from __future__ import annotations

import json
import re
import unicodedata
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .schema import EDGE_RELS, ENTITY_KINDS
from .store import PanoramaStore

__all__ = ["GENERATED_HEADER", "PAGE_KINDS", "generate_views"]

GENERATED_HEADER = (
    "<!-- GENERATED by research_harness.panorama.views — do not edit by hand. "
    "Regenerate with `rh panorama views`. -->"
)

#: Entity kinds that get a dedicated page under ``entities/<kind>/``.
PAGE_KINDS = ("system", "benchmark", "code_repo", "mechanism", "claim", "limitation")

_OPEN_STATUSES = ("unknown", "open")
_WEAK_STRENGTHS = ("none", "weak")
_SLUG_MAX_LEN = 80


# -- shared helpers (also used by context_pack.py) ---------------------------


def utc_timestamp() -> str:
    """Second-resolution UTC timestamp for the generation header."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def generated_header_block(direction_slug: str, generated_at: str) -> str:
    """Header prepended to every generated file; timestamp on its own line."""
    return (
        f"{GENERATED_HEADER}\n"
        f"<!-- generated_at: {generated_at} -->\n"
        f"<!-- direction: {direction_slug} -->\n"
    )


def one_line(text: str, limit: int = 160) -> str:
    """Collapse whitespace to a single line and cap length."""
    line = " ".join((text or "").split())
    if len(line) <= limit:
        return line
    return line[: limit - 1].rstrip() + "…"


def cell_label(cell: dict[str, Any]) -> str:
    parts = [cell["problem"], cell["mechanism"]]
    if cell.get("evidence_facet"):
        parts.append(cell["evidence_facet"])
    return " × ".join(parts)


def classify_cells(
    cells: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    """Split cells into (open, weak-evidence, contested) frontier buckets.

    A cell may appear in both the weak and contested buckets; open cells are
    excluded from the weak bucket (they are already listed as open).
    """
    open_cells = [c for c in cells if c["status"] in _OPEN_STATUSES]
    weak_cells = [
        c
        for c in cells
        if c["status"] not in _OPEN_STATUSES
        and c["evidence_strength"] in _WEAK_STRENGTHS
    ]
    contested_cells = [c for c in cells if c["status"] == "contested"]
    return open_cells, weak_cells, contested_cells


def sorted_cells(store: PanoramaStore, direction_id: int) -> list[dict[str, Any]]:
    return sorted(
        store.cells(direction_id),
        key=lambda c: (c["problem"], c["mechanism"], c["evidence_facet"], c["id"]),
    )


def sorted_verdicts(store: PanoramaStore, direction_id: int) -> list[dict[str, Any]]:
    """Live verdicts only — scoped, unexpired, and not superseded.

    Deny by default: a verdict recorded before schema v3, written without a
    scope, expired, or superseded is excluded here and surfaced separately by
    :func:`sorted_ineligible_verdicts`. Rendering the two in one undifferentiated
    ledger is how a stale conclusion keeps influencing the next round.
    """
    return sorted(
        store.active_verdicts(direction_id), key=lambda v: (v["decided_at"], v["id"])
    )


def sorted_ineligible_verdicts(
    store: PanoramaStore, direction_id: int
) -> list[dict[str, Any]]:
    """Quarantined, expired, superseded, and unscoped verdicts, for audit only."""
    return sorted(
        (
            verdict
            for verdict in store.verdicts(direction_id)
            if store.effective_eligibility(verdict) != "active"
        ),
        key=lambda v: (v["decided_at"], v["id"]),
    )


def _ineligible_reason(store: PanoramaStore, verdict: dict[str, Any]) -> str:
    if verdict.get("superseded_by"):
        return f"superseded by verdict {verdict['superseded_by']}"
    if verdict.get("eligibility") == "quarantined":
        return verdict.get("quarantine_reason") or "quarantined"
    if verdict.get("scope_status") == "legacy_unscoped":
        return verdict.get("quarantine_reason") or "no recorded scope"
    if store.effective_eligibility(verdict) != "active":
        return f"expired at {verdict.get('valid_until')}"
    return ""


def live_direction_edges(
    store: PanoramaStore, direction_id: int, entities: list[dict[str, Any]]
) -> list[dict[str, Any]]:
    """All live edges of the direction, deduped and ordered by edge id.

    The store has no direction-level edge listing, so this unions the
    per-entity ``edges_for`` results.
    """
    seen: dict[int, dict[str, Any]] = {}
    for ent in entities:
        for edge in store.edges_for(ent["id"], live_only=True):
            if edge.get("direction_id") == direction_id:
                seen[edge["id"]] = edge
    return [seen[edge_id] for edge_id in sorted(seen)]


# -- formatting internals ----------------------------------------------------


def _slugify(name: str, entity_id: int) -> str:
    normalized = unicodedata.normalize("NFKD", name)
    ascii_name = normalized.encode("ascii", "ignore").decode("ascii").lower()
    ascii_name = re.sub(r"[^a-z0-9]+", "-", ascii_name).strip("-")
    ascii_name = ascii_name[:_SLUG_MAX_LEN].rstrip("-") or "entity"
    return f"{ascii_name}-{entity_id}"


def _md_cell(value: Any) -> str:
    if not isinstance(value, str):
        value = json.dumps(value, ensure_ascii=False, sort_keys=True)
    text = " ".join(value.split()).replace("|", "\\|")
    return text or "—"


def _entity_ref(
    entity: dict[str, Any] | None,
    entity_id: int,
    page_rel_by_id: dict[int, str],
    *,
    from_entity_page: bool = False,
) -> str:
    if entity is None:
        return f"entity #{entity_id}"
    rel = page_rel_by_id.get(entity_id)
    if rel is None:
        return entity["name"]
    if from_entity_page:
        rel = "../" + rel[len("entities/") :]
    return f"[{entity['name']}]({rel})"


def _anchor_lines(anchor: dict[str, Any]) -> list[str]:
    lines: list[str] = []
    for label, key in (
        ("Keywords", "keywords"),
        ("Summary", "summary"),
        ("Insight", "insight"),
    ):
        value = (anchor.get(key) or "").strip()
        if value:
            lines.append(f"> **{label}:** {one_line(value, 500)}")
    quote = (anchor.get("quote") or "").strip()
    if quote:
        lines.append(f"> **Quote:** “{one_line(quote, 500)}”")
    source = (anchor.get("source_ref") or "").strip() or "(unspecified)"
    lines.append(f"> — source: {source}")
    return lines


def _cell_lines(
    cell: dict[str, Any],
    occupants: list[dict[str, Any]],
    anchors: list[dict[str, Any]],
    page_rel_by_id: dict[int, str],
) -> list[str]:
    lines = [
        f"- **{cell_label(cell)}** — status: {cell['status']}, "
        f"strength: {cell['evidence_strength']}, "
        f"last_verified: {cell['last_verified_at'] or 'never'}"
    ]
    if cell.get("notes"):
        lines.append(f"  - notes: {one_line(cell['notes'])}")
    if occupants:
        names = "; ".join(
            _entity_ref(occ, occ["id"], page_rel_by_id) for occ in occupants
        )
        lines.append(f"  - occupants: {names}")
    else:
        lines.append("  - occupants: none")
    for anchor in anchors:
        gist = one_line(
            anchor["summary"]
            or anchor["insight"]
            or anchor["keywords"]
            or anchor["quote"],
            120,
        )
        source = (anchor.get("source_ref") or "").strip() or "(unspecified)"
        lines.append(f"  - anchor: {gist} — {source}")
    return lines


# -- page renderers ----------------------------------------------------------


def _render_overview(
    direction: dict[str, Any],
    stats: dict[str, Any],
    entities: list[dict[str, Any]],
    page_rel_by_id: dict[int, str],
    header: str,
) -> str:
    lines: list[str] = [f"# {direction['title']}", ""]
    lines.append(f"_Direction: `{direction['slug']}`_")
    lines.append("")
    description = (direction.get("description") or "").strip()
    lines.append(description if description else "_No description recorded._")

    lines += ["", "## Stats", "", "| Metric | Value |", "| --- | --- |"]
    lines.append(f"| Entities (total) | {stats['entities_total']} |")
    by_kind = stats["entities_by_kind"]
    for kind in ENTITY_KINDS:
        if kind in by_kind:
            lines.append(f"| Entities: {kind} | {by_kind[kind]} |")
    lines.append(f"| Live edges | {stats['live_edges']} |")
    for status, count in sorted(stats["cells_by_status"].items()):
        lines.append(f"| Cells: {status} | {count} |")
    lines.append(f"| Verdicts | {stats['verdicts']} |")
    lines.append(f"| Anchors (store-wide) | {stats['anchors']} |")

    lines += ["", "## Entity index"]
    for kind in ENTITY_KINDS:
        kind_entities = [e for e in entities if e["kind"] == kind]
        if not kind_entities:
            continue
        lines += ["", f"### {kind} ({len(kind_entities)})", ""]
        for ent in kind_entities:
            ref = _entity_ref(ent, ent["id"], page_rel_by_id)
            summary = one_line(ent.get("summary") or "")
            lines.append(f"- {ref} — {summary}" if summary else f"- {ref}")

    return header + "\n" + "\n".join(lines) + "\n"


def _render_frontier(
    direction: dict[str, Any],
    cells: list[dict[str, Any]],
    occupants_by_cell: dict[int, list[dict[str, Any]]],
    anchors_by_cell: dict[int, list[dict[str, Any]]],
    verdicts: list[dict[str, Any]],
    edges: list[dict[str, Any]],
    entity_by_id: dict[int, dict[str, Any]],
    page_rel_by_id: dict[int, str],
    header: str,
    ineligible_verdicts: list[dict[str, Any]] | None = None,
) -> str:
    ineligible_verdicts = ineligible_verdicts or []
    open_cells, weak_cells, contested_cells = classify_cells(cells)

    def cell_section(title: str, bucket: list[dict[str, Any]]) -> list[str]:
        lines = ["", f"## {title}", ""]
        if not bucket:
            lines.append("_None._")
            return lines
        for cell in bucket:
            lines += _cell_lines(
                cell,
                occupants_by_cell.get(cell["id"], []),
                anchors_by_cell.get(cell["id"], []),
                page_rel_by_id,
            )
        return lines

    lines: list[str] = [f"# Frontier — {direction['title']}", ""]
    lines.append(f"_Direction: `{direction['slug']}`_")
    lines += cell_section("Open cells", open_cells)
    lines += cell_section("Weak-evidence cells", weak_cells)
    lines += cell_section("Contested cells", contested_cells)

    lines += ["", "## Verdict ledger (live)", ""]
    if verdicts:
        lines += [
            "| Claim | Verdict | Scope | Tool | Decided at | Valid until |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for verdict in verdicts:
            scope = f"{verdict.get('scope_kind', '')}: {verdict.get('scope_ref', '')}"
            lines.append(
                f"| {_md_cell(verdict['claim_text'])} "
                f"| {_md_cell(verdict['verdict'])} "
                f"| {_md_cell(scope)} "
                f"| {_md_cell(verdict['tool'])} "
                f"| {_md_cell(verdict['decided_at'])} "
                f"| {_md_cell(verdict.get('valid_until') or 'no expiry')} |"
            )
    else:
        lines.append("_No live verdicts._")

    if ineligible_verdicts:
        lines += [
            "",
            "## Verdict ledger (diagnostic only — must not influence ranking)",
            "",
            "These verdicts are recorded for audit. They are unscoped, expired, "
            "superseded, or quarantined, so they are evidence of what was once "
            "decided, not of what is true now. Re-certify before reusing any of "
            "them, and never treat a run of them as a sample of a research area.",
            "",
            "| Claim | Verdict | Decided at | Why not live |",
            "| --- | --- | --- | --- |",
        ]
        for verdict in ineligible_verdicts:
            lines.append(
                f"| {_md_cell(verdict['claim_text'])} "
                f"| {_md_cell(verdict['verdict'])} "
                f"| {_md_cell(verdict['decided_at'])} "
                f"| {_md_cell(verdict.get('ineligible_reason', ''))} |"
            )

    lines += ["", "## Contradictions", ""]
    contradictions = [e for e in edges if e["rel"] == "contradicts"]
    if contradictions:
        for edge in contradictions:
            src = _entity_ref(
                entity_by_id.get(edge["src_id"]), edge["src_id"], page_rel_by_id
            )
            dst = _entity_ref(
                entity_by_id.get(edge["dst_id"]), edge["dst_id"], page_rel_by_id
            )
            lines.append(f"- {src} contradicts {dst} (observed {edge['observed_at']})")
    else:
        lines.append("_No live `contradicts` edges._")

    return header + "\n" + "\n".join(lines) + "\n"


def _render_entity_page(
    entity: dict[str, Any],
    edges: list[dict[str, Any]],
    entity_by_id: dict[int, dict[str, Any]],
    page_rel_by_id: dict[int, str],
    anchors: list[dict[str, Any]],
    header: str,
) -> str:
    lines: list[str] = [f"# {entity['name']}", ""]
    lines.append(f"_Kind: `{entity['kind']}` · entity id: {entity['id']}_")
    lines.append("")
    summary = (entity.get("summary") or "").strip()
    lines.append(summary if summary else "_No summary recorded._")

    attrs = entity.get("attrs") or {}
    lines += ["", "## Attributes", ""]
    if attrs:
        lines += ["| Key | Value |", "| --- | --- |"]
        for key in sorted(attrs):
            lines.append(f"| {_md_cell(key)} | {_md_cell(attrs[key])} |")
    else:
        lines.append("_None._")

    ext_ids = entity.get("ext_ids") or {}
    lines += ["", "## External IDs", ""]
    if ext_ids:
        lines += ["| Scheme | Value |", "| --- | --- |"]
        for scheme in sorted(ext_ids):
            lines.append(f"| {_md_cell(scheme)} | {_md_cell(ext_ids[scheme])} |")
    else:
        lines.append("_None._")

    lines += ["", "## Edges"]
    wrote_edge = False
    for rel in EDGE_RELS:
        rel_edges = [e for e in edges if e["rel"] == rel]
        if not rel_edges:
            continue
        wrote_edge = True
        lines += ["", f"### {rel}", ""]
        entries: list[tuple[int, str, int, str]] = []
        for edge in rel_edges:
            outgoing = edge["src_id"] == entity["id"]
            other_id = edge["dst_id"] if outgoing else edge["src_id"]
            other = entity_by_id.get(other_id)
            ref = _entity_ref(other, other_id, page_rel_by_id, from_entity_page=True)
            other_kind = other["kind"] if other else "unknown"
            arrow = "→" if outgoing else "←"
            sort_name = other["name"].casefold() if other else str(other_id)
            entries.append(
                (
                    0 if outgoing else 1,
                    sort_name,
                    edge["id"],
                    f"- {arrow} {ref} ({other_kind})",
                )
            )
        for _, _, _, text in sorted(entries):
            lines.append(text)
    if not wrote_edge:
        lines += ["", "_No live edges._"]

    lines += ["", "## Evidence anchors", ""]
    if anchors:
        blocks = ["\n".join(_anchor_lines(anchor)) for anchor in anchors]
        lines.append("\n\n".join(blocks))
    else:
        lines.append("_No evidence anchors recorded._")

    return header + "\n" + "\n".join(lines) + "\n"


# -- entry point -------------------------------------------------------------


def generate_views(store: PanoramaStore, direction_slug: str) -> dict[str, int]:
    """Regenerate the L2 markdown vault for one direction.

    Writes ``00-overview.md``, ``frontier.md``, and one page per entity of a
    kind in :data:`PAGE_KINDS` under ``entities/<kind>/``; removes stale entity
    pages (within ``entities/`` only). Returns
    ``{"files_written", "entity_pages", "stale_removed"}``.
    """
    direction = store.direction(direction_slug)
    if direction is None:
        raise ValueError(f"unknown panorama direction: {direction_slug!r}")
    direction_id = int(direction["id"])
    header = generated_header_block(direction_slug, utc_timestamp())

    entities = sorted(
        store.entities(direction_id),
        key=lambda e: (e["name"].casefold(), e["id"]),
    )
    entity_by_id = {e["id"]: e for e in entities}
    edges = live_direction_edges(store, direction_id, entities)
    cells = sorted_cells(store, direction_id)
    verdicts = sorted_verdicts(store, direction_id)
    ineligible_verdicts = [
        {**verdict, "ineligible_reason": _ineligible_reason(store, verdict)}
        for verdict in sorted_ineligible_verdicts(store, direction_id)
    ]
    occupants_by_cell = {c["id"]: store.cell_occupants(c["id"]) for c in cells}
    anchors_by_cell = {
        c["id"]: sorted(store.anchors_for("cell", c["id"]), key=lambda a: a["id"])
        for c in cells
    }
    stats = store.stats(direction_id)

    page_rel_by_id: dict[int, str] = {
        ent["id"]: f"entities/{ent['kind']}/{_slugify(ent['name'], ent['id'])}.md"
        for ent in entities
        if ent["kind"] in PAGE_KINDS
    }

    vault = store.vault_dir
    vault.mkdir(parents=True, exist_ok=True)
    files_written = 0
    entity_pages = 0
    expected: set[Path] = set()

    for ent in entities:
        rel = page_rel_by_id.get(ent["id"])
        if rel is None:
            continue
        path = vault / rel
        expected.add(path)
        anchors = sorted(store.anchors_for("entity", ent["id"]), key=lambda a: a["id"])
        ent_edges = [e for e in edges if ent["id"] in (e["src_id"], e["dst_id"])]
        page = _render_entity_page(
            ent, ent_edges, entity_by_id, page_rel_by_id, anchors, header
        )
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(page, encoding="utf-8")
        files_written += 1
        entity_pages += 1

    stale_removed = 0
    entities_dir = vault / "entities"
    if entities_dir.exists():
        for candidate in sorted(entities_dir.rglob("*.md")):
            if candidate not in expected:
                candidate.unlink()
                stale_removed += 1
        subdirs = [p for p in entities_dir.rglob("*") if p.is_dir()]
        for subdir in sorted(subdirs, reverse=True):
            if not any(subdir.iterdir()):
                subdir.rmdir()

    overview = _render_overview(direction, stats, entities, page_rel_by_id, header)
    (vault / "00-overview.md").write_text(overview, encoding="utf-8")
    files_written += 1

    frontier = _render_frontier(
        direction,
        cells,
        occupants_by_cell,
        anchors_by_cell,
        verdicts,
        edges,
        entity_by_id,
        page_rel_by_id,
        header,
        ineligible_verdicts=ineligible_verdicts,
    )
    (vault / "frontier.md").write_text(frontier, encoding="utf-8")
    files_written += 1

    return {
        "files_written": files_written,
        "entity_pages": entity_pages,
        "stale_removed": stale_removed,
    }
